#!/usr/bin/env python3
"""Generate custom/native thumb-gesture keymaps from one physical ZMK layout."""
# SPDX-License-Identifier: GPL-2.0-or-later
import argparse
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
LAYERS = ["COLEMAK", "BASE", "FPS", "SYM", "NUM", "FUNC", "ADJUST", "DJMAX", "MOUSE"]
NATIVE_BINDINGS = {"&tg 0": "&native_shift_sym",
                   "&tg 1": "&native_enter_ctrl LCTRL RET",
                   "&tg 2": "&native_ctrl_alt"}
KEYMAPS = {"custom": "halcyon_elora.keymap", "native": "halcyon_elora_native.keymap"}
CUSTOM_GESTURES = '''        tg: thumb_gestures {
            compatible = "aefreedman,thumb-gestures";
            #binding-cells = <1>;
            symbol-layer = <SYM>;
        };
'''

HEADER = """/* SPDX-License-Identifier: GPL-2.0-or-later
 * Generated by scripts/generate_keymap.py from config/layout.json.
 * Original QMK keymap: Copyright 2020 gtips, modified by aefreedman.
 * Edit layout.json for bindings and the generator/includes for behaviors, then regenerate.
 */
#define ZMK_POINTING_DEFAULT_MOVE_VAL 2000
#include <behaviors.dtsi>
#include <dt-bindings/zmk/keys.h>
#include <dt-bindings/zmk/pointing.h>

#define COLEMAK 0
#define QWERTY  1
#define FPS     2
#define SYM     3
#define NUM     4
#define FUNC    5
#define ADJUST  6
#define DJMAX   7
#define MOUSE   8

&mmv_input_listener {
    input-processors = <&pointer_speed>;
};

&lt {
    tapping-term-ms = <200>;
    // A tap must not force the next hold into repeating Backspace/Delete.
    quick-tap-ms = <0>;
    flavor = "hold-preferred";
};

/ {
    pointer_speed: runtime_mouse_speed {
        compatible = "aefreedman,mouse-speed-scaler";
        #input-processor-cells = <0>;
        track-remainders;
    };
    behaviors {
        ms_adjust: mouse_speed_adjust {
            compatible = "aefreedman,mouse-speed";
            #binding-cells = <1>;
        };
        ms_down: mouse_speed_down {
            compatible = "zmk,behavior-tap-dance";
            #binding-cells = <0>;
            tapping-term-ms = <200>;
            bindings = <&ms_adjust 0>, <&ms_adjust 2>;
        };
        ms_up: mouse_speed_up {
            compatible = "zmk,behavior-tap-dance";
            #binding-cells = <0>;
            tapping-term-ms = <200>;
            bindings = <&ms_adjust 1>, <&ms_adjust 2>;
        };
__THUMB_GESTURES__        base_select: base_selection {
            compatible = "aefreedman,base-select";
            #binding-cells = <1>;
        };
        ms_fast: mouse_fast_mode {
            compatible = "zmk,behavior-tap-dance";
            #binding-cells = <0>;
            tapping-term-ms = <200>;
            bindings = <&ms_adjust 3>, <&ms_adjust 4>;
        };
        ms_precision: mouse_precision_mode {
            compatible = "zmk,behavior-tap-dance";
            #binding-cells = <0>;
            tapping-term-ms = <200>;
            bindings = <&ms_adjust 5>, <&ms_adjust 6>;
        };
    };
    keymap {
        compatible = "zmk,keymap";
"""

# Position groups and horizontal offsets in two eight-column halves.
ROWS = [(range(0, 6), range(6, 12), 0, 2),
        (range(12, 18), range(18, 24), 0, 2),
        (range(24, 30), range(30, 36), 0, 2),
        (range(36, 44), range(44, 52), 0, 0),
        (range(52, 57), range(57, 62), 3, 0),
        (range(62, 67), range(67, 72), 0, 3)]


def column_widths(layers):
    widths = [[0] * 8 for _ in range(2)]
    for _, _, bindings in layers:
        for left, right, lo, ro in ROWS:
            for side, positions, offset in [(0, left, lo), (1, right, ro)]:
                for col, pos in enumerate(positions, offset):
                    widths[side][col] = max(widths[side][col], len(bindings[pos]))
    return widths


def render_layer(name, label, bindings):
    widths = column_widths([(name, label, bindings)])
    left_width = sum(widths[0]) + 7
    text = f'\n        {name.lower()}_layer {{\n            display-name = "{label}";\n'
    text += "            // " + "LEFT".ljust(left_width) + "      RIGHT\n"
    text += "            bindings = <\n"
    for left, right, lo, ro in ROWS:
        halves = []
        for side, positions, offset in [(0, left, lo), (1, right, ro)]:
            cells = [""] * 8
            for col, pos in enumerate(positions, offset):
                cells[col] = bindings[pos]
            halves.append(" ".join(cell.ljust(width) for cell, width in zip(cells, widths[side])))
        text += "                " + (halves[0] + "      " + halves[1]).rstrip() + "\n"
    text += "            >;\n"
    # Sensor order: left module, right module, left soldered, right soldered.
    text += "            sensor-bindings = <&inc_dec_kp C_VOL_UP C_VOL_DN &inc_dec_kp C_VOL_UP C_VOL_DN &inc_dec_kp C_VOL_UP C_VOL_DN &inc_dec_kp C_VOL_UP C_VOL_DN>;\n        };\n"
    return text


def build_layers(gestures="custom"):
    if gestures not in KEYMAPS:
        raise ValueError(f"Unknown thumb gesture backend: {gestures}")
    data = json.loads((ROOT / "config/layout.json").read_text())
    assert [layer["name"] for layer in data["layers"]] == LAYERS
    layers = []
    for layer in data["layers"]:
        assert [len(row) for row in layer["rows"]] == [12, 12, 12, 16, 10, 10]
        bindings = [binding for row in layer["rows"] for binding in row]
        assert all(isinstance(binding, str) and binding.startswith("&") for binding in bindings)
        if gestures == "native":
            bindings = [NATIVE_BINDINGS.get(binding, binding) for binding in bindings]
        layers.append((layer["name"], layer["label"], bindings))
    return layers


def generate(gestures="custom"):
    layers = build_layers(gestures)
    behavior = CUSTOM_GESTURES if gestures == "custom" else '#include "native_thumb_gestures.dtsi"\n'
    header = HEADER.replace("__THUMB_GESTURES__", behavior)
    return header + "".join(render_layer(name, label, bindings)
                           for name, label, bindings in layers) + "    };\n};\n"

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--gestures", choices=["custom", "native", "both"], default="both")
    args = parser.parse_args()
    backends = KEYMAPS if args.gestures == "both" else [args.gestures]
    for backend in backends:
        path = ROOT / "config" / KEYMAPS[backend]
        content = generate(backend)
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"{backend} keymap is stale; run scripts/generate_keymap.py")
            print(f"{backend} keymap is current")
        else:
            path.write_text(content)
            print(path)
