#!/usr/bin/env python3
"""Generate the Elora port from the frozen, attributed QMK reference. No network."""
# SPDX-License-Identifier: GPL-2.0-or-later
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
LAYERS = ["COLEMAK", "BASE", "FPS", "SYM", "NUM", "FUNC", "ADJUST", "DJMAX"]
# Each original physical Reviung position has exactly one destination.
POSITIONS = [*range(12, 36), *range(36, 42), *range(46, 52), 53, 54, 58, 59, 60]
SPECIAL = {
    "_______": "&trans", "XXXXXXX": "&none", "ADJUST": "&mo ADJUST",
    "COLEMAK": "&base_select COLEMAK", "QWERTY": "&base_select QWERTY",
    "FPS": "&base_select FPS", "DJMAX": "&tog DJMAX",
    "TH_NUM_BSPC": "&lt NUM BSPC", "TH_FUNC_DEL": "&lt FUNC DEL",
    "DK_SHIFT_SYM": "&rd 0", "DK_ENTER_CTRL": "&rd 1", "DK_CTRL_ALT": "&rd 2",
    "QK_RBT": "&sys_reset", "QK_BOOT": "&bootloader",
}
KEYS = {
    "LCTL": "LCTRL", "LSFT": "LSHFT", "RSFT": "RSHFT", "ENT": "RET",
    "SPC": "SPACE", "SCLN": "SEMI", "QUOT": "SQT", "COMM": "COMMA",
    "SLSH": "FSLH", "RGHT": "RIGHT", "PGUP": "PG_UP", "PGDN": "PG_DN",
    "INSERT": "INS", "PDOT": "KP_DOT", "VOLD": "C_VOL_DN", "VOLU": "C_VOL_UP",
    "MINS": "MINUS", "MUTE": "C_MUTE", "MPRV": "C_PREV", "MPLY": "C_PLAY_PAUSE", "MNXT": "C_NEXT",
    "LPRN": "LPAR", "RPRN": "RPAR", "PSLS": "KP_DIVIDE", "PAST": "KP_MULTIPLY",
    "PPLS": "KP_PLUS", "UNDS": "UNDER", "DLR": "DLLR", "LCBR": "LBRC",
    "RCBR": "RBRC", "PERC": "PRCNT", "BSLS": "BSLH", "LBRC": "LBKT",
    "RBRC": "RBKT", "GRV": "GRAVE", "DQUO": "DQT", "EQL": "EQUAL",
    "AMPR": "AMPS", "QUES": "QMARK", "EXLM": "EXCL",
}

def source_layers():
    source = (ROOT / "reference/reviung41/keymap.c").read_text()
    return {name: [x.strip() for x in body.split(",") if x.strip()]
            for name, body in re.findall(r"\[_(\w+)\] = LAYOUT_reviung41\((.*?)\n    \)", source, re.S)}

def binding(token):
    if token in SPECIAL:
        return SPECIAL[token]
    if token.startswith("UG_"):
        return "&none"  # RGB intentionally removed.
    if not token.startswith("KC_"):
        raise ValueError(f"Unknown QMK token: {token}")
    key = token[3:]
    return "&kp " + ("N" + key if key.isdigit() else KEYS.get(key, key))

HEADER = """/* SPDX-License-Identifier: GPL-2.0-or-later
 * Generated by scripts/generate_keymap.py from reference/reviung41/keymap.c.
 * Original QMK keymap: Copyright 2020 gtips, modified by aefreedman.
 * Edit the generator/reference deliberately, then regenerate.
 */
#include <behaviors.dtsi>
#include <dt-bindings/zmk/keys.h>

#define COLEMAK 0
#define QWERTY  1
#define FPS     2
#define SYM     3
#define NUM     4
#define FUNC    5
#define ADJUST  6
#define DJMAX   7

&lt {
    tapping-term-ms = <200>;
    quick-tap-ms = <200>;
    flavor = "tap-preferred";
};

/ {
    behaviors {
        rd: reviung_dance {
            compatible = "aefreedman,reviung-dance";
            #binding-cells = <1>;
            symbol-layer = <SYM>;
        };
        base_select: reviung_base {
            compatible = "aefreedman,reviung-base";
            #binding-cells = <1>;
        };
    };
    keymap {
        compatible = "zmk,keymap";
"""

def generate():
    original = source_layers()
    text = HEADER
    labels = {"BASE": "QWERTY", "NUM": "Numbers + navigation", "FUNC": "Function + media"}
    for name in LAYERS:
        keys = original[name]
        assert len(keys) == 41, (name, len(keys))
        bindings = ["&none"] * 72
        for pos, token in zip(POSITIONS, keys):
            bindings[pos] = binding(token)
        text += f'\n        {name.lower()}_layer {{\n            display-name = "{labels.get(name, name.title())}";\n            bindings = <\n'
        for start, end in [(0, 12), (12, 24), (24, 36), (36, 52), (52, 62), (62, 72)]:
            text += "                " + "  ".join(f"{b:<20}" for b in bindings[start:end]).rstrip() + "\n"
        text += "            >;\n"
        # Sensor order: left module, right module, left soldered, right soldered.
        # Encoder press and all other module button positions remain unassigned.
        text += "            sensor-bindings = <&inc_dec_kp C_VOL_UP C_VOL_DN &inc_dec_kp C_VOL_UP C_VOL_DN &inc_dec_kp C_VOL_UP C_VOL_DN &inc_dec_kp C_VOL_UP C_VOL_DN>;\n        };\n"
    return text + "    };\n};\n"

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "config/halcyon_elora.keymap"
    content = generate()
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit("Generated keymap is stale; run scripts/generate_keymap.py")
        print("Generated keymap is current")
    else:
        path.write_text(content)
        print(path)
